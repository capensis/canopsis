// Command fieldsgen generates OpenAPI definitions of sortable and searchable fields
// of public API endpoints from the lists which are used for validation.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"

	"git.canopsis.net/canopsis/canopsis-community/community/go-engines-community/lib/api/public/alarm"
	"git.canopsis.net/canopsis/canopsis-community/community/go-engines-community/lib/api/public/entity"
	"go.yaml.in/yaml/v3"
)

const header = "# Code generated by fieldsgen. DO NOT EDIT.\n"

const (
	sortDescription = "Comma separated list of `field:direction`, applied in order. " +
		"The direction is `asc` or `desc`, and may be omitted to sort ascending."
	searchByDescription          = "Field to restrict the full text search to."
	searchByParameterDescription = "restrict the full text search to these fields"
)

func main() {
	out := flag.String("o", "fields_swagger.yaml", "output file")
	flag.Parse()

	b, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	err = os.WriteFile(*out, b, 0o644) //nolint:gosec
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() ([]byte, error) {
	definitions := map[string]any{
		"alarm.Sort":          alarm.SortableFields().SortSchema(sortDescription),
		"alarm.SearchByField": alarm.SearchableFields().FieldSchema(searchByDescription),
		"alarm.StepSort":      alarm.StepSortableFields().SortSchema(sortDescription),

		"entity.Sort":          entity.SortableFields().SortSchema(sortDescription),
		"entity.SearchByField": entity.SearchableFields().FieldSchema(searchByDescription),
	}

	parameters := map[string]any{
		"alarm.Sort":      alarm.SortableFields().SortParameter("alarm.Sort", sortDescription, alarm.DefaultSort),
		"alarm.SearchBy":  alarm.SearchableFields().SearchByParameter("alarm.SearchByField", searchByParameterDescription),
		"alarm.StepSort":  alarm.StepSortableFields().SortParameter("alarm.StepSort", sortDescription, "t:desc"),
		"entity.Sort":     entity.SortableFields().SortParameter("entity.Sort", sortDescription, entity.DefaultSort),
		"entity.SearchBy": entity.SearchableFields().SearchByParameter("entity.SearchByField", searchByParameterDescription),
	}

	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	err := enc.Encode(map[string]any{"definitions": definitions, "parameters": parameters})
	if err != nil {
		return nil, err
	}

	err = enc.Close()
	if err != nil {
		return nil, err
	}

	return buf.Bytes(), nil
}
